const {chromium}=require('playwright');
const {spawn}=require('node:child_process');
const readline=require('node:readline');
const path=require('node:path');
const assert=require('node:assert/strict');
const {randomUUID}=require('node:crypto');
(async()=>{
 const fixture=spawn('python',['-u',path.join(__dirname,'serveFeedbackAdmin.py')],{stdio:['ignore','pipe','pipe']});
 let browser;
 try {
  const config=await new Promise((resolve,reject)=>{const lines=readline.createInterface({input:fixture.stdout});const timer=setTimeout(()=>reject(Error('Fixture startup timeout')),20000);lines.once('line',line=>{clearTimeout(timer);resolve(JSON.parse(line));});fixture.once('exit',code=>{clearTimeout(timer);reject(Error('Fixture exited '+code));});fixture.stderr.on('data',d=>process.stderr.write(d));});
  browser=await chromium.launch({channel:'msedge',headless:true});
  const page=await browser.newPage({viewport:{width:1200,height:900}});
  await page.goto(config.origin+'/feedback-admin');
  await page.getByLabel('管理密码',{exact:true}).fill(config.password);
  await page.getByRole('button',{name:'登录后台'}).click();
  await page.getByText('已安全登录',{exact:true}).waitFor();
  assert.equal(await page.locator('article').count(),2);
  assert.equal(await page.evaluate(()=>Boolean(window.xssExecuted)),false);
  assert.equal(await page.locator('article img').count(),0);
  const card=page.locator('article').filter({has:page.getByRole('heading',{name:config.report.title,exact:true})});
  await card.getByLabel('报告处理分类').selectOption('spam');
  await card.getByRole('button',{name:'保存分类'}).click();
  await page.getByText('处理分类已保存',{exact:true}).waitFor();
  await card.getByRole('button',{name:'禁用此设备'}).click();
  await page.getByLabel('禁用天数').fill('2');
  await page.getByLabel('处理原因').fill('测试：重复提交无关内容');
  await page.getByRole('button',{name:'确认禁用'}).click();
  await page.getByText('反馈限制已生效，到期自动恢复',{exact:true}).waitFor();
  const submit=report=>page.request.post(config.origin+'/api/kennysvideo/feedback',{data:report,headers:{Origin:config.origin}});
  const blocked=await submit({...config.report,request_id:randomUUID()});assert.equal(blocked.status(),423);
  const other=await submit({...config.report,request_id:randomUUID(),device_id:randomUUID()});assert.equal(other.status(),202);
  await page.screenshot({path:path.join(__dirname,'../dist-windows/KennysVideo-feedback-admin-desktop.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.screenshot({path:path.join(__dirname,'../dist-windows/KennysVideo-feedback-admin-mobile.png'),fullPage:true});
  await page.getByRole('button',{name:'禁用管理',exact:true}).click();
  await page.getByRole('heading',{name:'有效禁用',exact:true}).waitFor();
  page.once('dialog',d=>d.accept());
  await page.getByRole('button',{name:'解除禁用',exact:true}).click();
  await page.getByText('反馈限制已解除',{exact:true}).waitFor();
  assert.equal((await submit({...config.report,request_id:randomUUID()})).status(),202);
  await page.getByRole('button',{name:'操作记录',exact:true}).click();
  await page.getByRole('heading',{name:'操作记录',exact:true}).waitFor();
  assert.equal(await page.locator('article').count(),3);
  await page.getByRole('button',{name:'修改密码',exact:true}).click();
  const passwordGeometry=await page.locator('#passwordDialog').boundingBox();
  assert(passwordGeometry.x>=0&&passwordGeometry.x+passwordGeometry.width<=390&&passwordGeometry.height<=844);
  await page.locator('#passwordDialog').screenshot({path:path.join(__dirname,'../dist-windows/KennysVideo-admin-password-dialog.png')});
  await page.getByLabel('当前密码',{exact:true}).fill(config.password);
  await page.getByLabel('新密码',{exact:true}).fill('new-local-test-password');
  await page.getByLabel('确认新密码',{exact:true}).fill('mismatch');
  await page.getByRole('button',{name:'保存新密码',exact:true}).click();
  await page.getByText('两次输入的新密码不一致',{exact:true}).waitFor();
  await page.getByLabel('确认新密码',{exact:true}).fill('new-local-test-password');
  await page.getByRole('button',{name:'保存新密码',exact:true}).click();
  await page.getByText('密码已修改，所有会话已退出，请用新密码重新登录',{exact:true}).waitFor();
  await page.getByLabel('管理密码',{exact:true}).fill('new-local-test-password');
  await page.getByRole('button',{name:'登录后台',exact:true}).click();
  await page.getByText('已安全登录',{exact:true}).waitFor();
  await page.getByRole('button',{name:'退出登录',exact:true}).click();
  await page.getByRole('heading',{name:'管理员登录'}).waitFor();
  assert.equal((await page.request.get(config.origin+'/feedback-admin/reports')).status(),401);
  console.log('PASS real admin UI → local HTTP/SQLite: login, secure cookie, safe user content rendering, review, 2-day ban, same-IP isolation, unban, audit, password confirmation/change/relogin, logout, 390px/1200px layout; no email sent');
 } finally {if(browser)await browser.close();fixture.kill();}
})().catch(error=>{console.error(error);process.exitCode=1;});
